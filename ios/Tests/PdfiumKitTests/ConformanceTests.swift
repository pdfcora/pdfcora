import XCTest
import CryptoKit
@testable import PdfiumKit

/// Locates the repository from this file's compile-time path, so the shared corpus and
/// expectations are found without bundling them as test resources.
enum Repo {
    static let root = URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent()   // PdfiumKitTests
        .deletingLastPathComponent()   // Tests
        .deletingLastPathComponent()   // ios
        .deletingLastPathComponent()   // repo root

    static var corpus: URL { root.appendingPathComponent("conformance/corpus") }
    static var expectationsURL: URL { root.appendingPathComponent("conformance/expectations.json") }
}

struct Expectations: Decodable {
    struct Page: Decodable {
        let width: Double
        let height: Double
        let charCount: Int?
        let textSha256: String?
        let textContains: [String]?
    }
    /// Generated by `pdfsig`, not PDFium, so these cannot be satisfied by a bug in
    /// our own reader.
    struct Signature: Decodable {
        let subFilter: String
        let byteRange: [Int]
        let coversWholeDocument: Bool
        let signatureValid: Bool
        let certificateTrusted: Bool
    }
    struct Document: Decodable {
        let category: String
        let opens: Bool
        let openError: String?
        let pageCount: Int?
        let pages: [Page]?
        let metadata: [String: String]?
        let signatures: [Signature]?
    }
    let engine: String
    let documents: [String: Document]
}

private func isValid(_ verdict: PdfSignatureValidity) -> Bool {
    if case .valid = verdict { return true }
    return false
}

final class ConformanceTests: LicensedTestCase {
    private static var expectations: Expectations = {
        let data = try! Data(contentsOf: Repo.expectationsURL)
        return try! JSONDecoder().decode(Expectations.self, from: data)
    }()

    func testExpectationsFileIsPresentAndNonEmpty() {
        XCTAssertFalse(Self.expectations.documents.isEmpty,
                       "conformance/expectations.json is empty — run node conformance/generate.mjs")
    }

    func testEngineRevisionMatchesExpectations() {
        XCTAssertEqual(PdfDocument.engineVersion, Self.expectations.engine)
    }

    /// The core conformance run: every corpus document, checked against the shared contract.
    func testAllCorpusDocumentsMatchExpectations() async throws {
        var checked = 0
        for (name, expected) in Self.expectations.documents {
            let url = Repo.corpus.appendingPathComponent(name)
            let data = try Data(contentsOf: url)

            if !expected.opens {
                do {
                    _ = try await PdfDocument(data: data)
                    XCTFail("\(name): expected open to fail with \(expected.openError ?? "?")")
                } catch let error as PdfError {
                    assertOpenError(error, matches: expected.openError, for: name)
                }
                checked += 1
                continue
            }

            let doc = try await PdfDocument(data: data)
            let count = await doc.pageCount
            XCTAssertEqual(count, expected.pageCount ?? -1, "\(name): page count")

            if let pages = expected.pages {
                for (i, expectedPage) in pages.enumerated() {
                    let page = try await doc.page(i)
                    let size = try await page.size
                    XCTAssertEqual(size.width, expectedPage.width, accuracy: 0.01, "\(name) page \(i) width")
                    XCTAssertEqual(size.height, expectedPage.height, accuracy: 0.01, "\(name) page \(i) height")

                    if let expectedCount = expectedPage.charCount {
                        let actual = try await page.text.characterCount
                        XCTAssertEqual(actual, expectedCount, "\(name) page \(i) character count")
                    }
                    if let expectedHash = expectedPage.textSha256 {
                        let text = try await page.text.string()
                        XCTAssertEqual(Self.textHash(text), expectedHash,
                            "\(name) page \(i) text differs from the reference engine; got \(text.prefix(60))")
                        for anchor in expectedPage.textContains ?? [] {
                            XCTAssertTrue(Self.collapsed(text).contains(anchor),
                                "\(name) page \(i) missing expected text \(anchor)")
                        }
                    }
                }

                if let expectedSignatures = expected.signatures {
                    let actual = try await doc.signatures()
                    XCTAssertEqual(actual.count, expectedSignatures.count, "\(name) signature count")
                    for (i, expectedSignature) in expectedSignatures.enumerated()
                    where i < actual.count {
                        XCTAssertEqual(actual[i].subFilter, expectedSignature.subFilter,
                            "\(name) signature \(i) sub-filter")
                        XCTAssertEqual(actual[i].byteRange, expectedSignature.byteRange,
                            "\(name) signature \(i) byte range")
                        XCTAssertEqual(actual[i].coversWholeDocument,
                            expectedSignature.coversWholeDocument,
                            "\(name) signature \(i) coverage")

                        // pdfsig reports integrity and trust separately, and so must we.
                        // With the signer's own certificate as an anchor the verdict must
                        // be valid, which can only happen if the signature verifies; with
                        // no anchors it must be untrusted, never valid.
                        let cms = try CmsSignedData.parse([UInt8](actual[i].contents))
                        let root = Data(try XCTUnwrap(cms.certificates.last))
                        let anchored = await doc.verify(
                            actual[i], options: PdfVerifyOptions(trustAnchors: [root]))
                        XCTAssertEqual(isValid(anchored), expectedSignature.signatureValid,
                            "\(name) signature \(i) cryptographic validity")

                        let unanchored = await doc.verify(actual[i])
                        XCTAssertEqual(isValid(unanchored), expectedSignature.certificateTrusted,
                            "\(name) signature \(i) trust without anchors")
                    }
                }
            }
            await doc.close()
            checked += 1
        }
        XCTAssertEqual(checked, Self.expectations.documents.count)
    }

    /// Must match conformance/generate.mjs exactly — see the note there on portability.
    private static let stripped: Set<UInt32> = [
        0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x20, 0xa0, 0x2028, 0x2029, 0x202f, 0x3000,
    ]

    private static func normalize(_ text: String) -> String {
        String(text.unicodeScalars.filter { !stripped.contains($0.value) })
    }

    private static func textHash(_ text: String) -> String {
        let digest = SHA256.hash(data: Data(normalize(text).utf8))
        return digest.map { String(format: "%02x", $0) }.joined()
    }

    /// Whitespace collapsed to single spaces, for the human-readable anchor only.
    private static func collapsed(_ text: String) -> String {
        text.split(whereSeparator: { $0.isWhitespace }).joined(separator: " ")
    }

    private func assertOpenError(_ error: PdfError, matches expected: String?, for name: String) {
        switch (error, expected) {
        case (.passwordRequired, "password"), (.wrongPassword, "password"): break
        case (.corrupt, "format"), (.corrupt, "file"): break
        case (.unsupportedSecurity, "security"): break
        default:
            XCTFail("\(name): error \(error) does not match expected \(expected ?? "nil")")
        }
    }
}
